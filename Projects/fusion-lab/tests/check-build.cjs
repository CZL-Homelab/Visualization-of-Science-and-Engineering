'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert.ok(!/<script[^>]+src=|<link[^>]+rel=["']stylesheet|@import\s|<!-- LAB_|\/\* LAB_STYLES/.test(html));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(ids.length, new Set(ids).size, 'unique HTML ids');
const context = {FL: {}};
vm.createContext(context);
for (const file of ['core', 'reference', 'content']) vm.runInContext(fs.readFileSync(path.join(root, `src/${file}.js`), 'utf8'), context);
const {SCENES, CHAPTERS} = context.FL.content;
assert.equal(SCENES.length, 42);
assert.equal(CHAPTERS.length, 7);
assert.equal(new Set(SCENES.map(s => s.id)).size, SCENES.length);
for (const m of context.FL.ref.MYTHS) assert.ok(SCENES.some(s => s.id === m.go), m.go);
for (const rule of context.FL.ref.RULES) for (const source of rule.src) assert.ok(context.FL.ref.SOURCES[source], source);
for (const match of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
assert.ok(html.indexOf("czl-lab-theme") < html.indexOf('<body>'));
assert.ok(html.includes('THREE') && html.includes('aria-current="page"'));
console.log('PASS: offline packaging, embedded script syntax, references and lesson navigation.');
